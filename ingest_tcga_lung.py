"""Build the tcga-lung casebank from public, de-identified TCGA-LUAD data.

This is a *recipe*: it fetches real report text at run time and writes cases
into ``pack/casebank/cases/``. The built cases are committed alongside it —
both upstream sources allow redistribution with attribution (see below).

Sources (public, de-identified, open-access):

  * Pathology report text — NCI Genomic Data Commons (GDC) open-access tier,
    https://gdc.cancer.gov (REST API at https://api.gdc.cancer.gov). Each
    patient's pathology report is an open-access PDF (data_type
    "Pathology Report"); text is extracted locally with pypdf.
    Attribution per GDC / TCGA publication guidelines: data generated by the
    TCGA Research Network (https://www.cancer.gov/tcga), project TCGA-LUAD,
    accessed via the GDC Data Portal.

  * Clinical fields (site, AJCC stage/TNM, smoking history) — GDC ``/cases``
    endpoint, same project and attribution.

  * Molecular alterations (best-effort enrichment) — cBioPortal public API,
    study ``luad_tcga``. cBioPortal data is available under the Open Database
    License (ODbL) v1.0: attribution + share-alike for the database. Cite
    Cerami et al., Cancer Discov 2012 (PMID 22588877) and Gao et al.,
    Sci Signal 2013 (PMID 23550210).

No Hugging Face dependency: earlier revisions of this recipe pulled report
text from the Lab-Rasool/TCGA packaging (CC-BY-NC-ND 4.0), which blocked
commercial use and republication. The same reports fetched directly from the
GDC open tier carry no such restriction, and the locally extracted text is
equivalent or better (the NC-ND packaging was itself an OCR of these PDFs).

Determinism: the patient barcodes are pinned below. They were originally
selected as the first 8 TCGA-LUAD barcodes (sorted) whose pathology report
text passed validation (>= 200 chars, mentions adenocarcinoma) and whose
clinical record carries an AJCC pathologic stage; pinning keeps case ids
stable for the pack, runs, and dossiers that reference them.

Ground truth is derived ONLY where the data determines it and the token is
verified present in the element that carries it; softer items are left empty
for physician adjudication via the review UI.

Requires: ``pip install pypdf`` (pure-Python PDF text extraction).
"""

from __future__ import annotations

import io
import json
import re
import sys
import urllib.parse
import urllib.request
from pathlib import Path

try:
    from pypdf import PdfReader
except ImportError:  # pragma: no cover
    sys.exit("pypdf is required: pip install pypdf")

GDC_API = "https://api.gdc.cancer.gov"
CASES_DIR = Path(__file__).parent / "pack" / "casebank" / "cases"
DIAGNOSIS_TOKEN = "adenocarcinoma"

# Pinned TCGA-LUAD patients (see module docstring for selection provenance).
BARCODES = [
    "TCGA-05-4245", "TCGA-05-4249", "TCGA-05-4382", "TCGA-05-4384",
    "TCGA-05-4389", "TCGA-05-4390", "TCGA-05-4396", "TCGA-05-4397",
]

# Actionable lung-adenocarcinoma driver genes, with NCBI Entrez ids (cBioPortal
# requires an explicit gene list). Order = clinical priority for the "actionable
# alteration" the tumor board would name first.
ACTIONABLE_GENES = {
    "EGFR": 1956, "ALK": 238, "ROS1": 6098, "BRAF": 673,
    "KRAS": 3845, "MET": 4233, "ERBB2": 2064, "RET": 5979,
}


def _request(url: str, body: bytes | None = None,
             content_type: str | None = None) -> bytes:
    headers = {"User-Agent": "tcga-lung-ingest"}
    if content_type:
        headers["Content-Type"] = content_type
    req = urllib.request.Request(url, data=body, headers=headers,
                                 method="POST" if body else "GET")
    last: Exception | None = None
    for _ in range(5):  # tolerate transient upstream 5xx
        try:
            with urllib.request.urlopen(req, timeout=120) as resp:
                return resp.read()
        except urllib.error.HTTPError as exc:
            last = exc
            if exc.code < 500:
                raise
        except urllib.error.URLError as exc:
            last = exc
    raise RuntimeError(f"request failed after retries: {url}") from last


def gdc_query(endpoint: str, filters: dict, fields: list[str], size: int) -> list[dict]:
    q = urllib.parse.urlencode({
        "filters": json.dumps(filters),
        "fields": ",".join(fields),
        "size": size,
    })
    data = json.loads(_request(f"{GDC_API}/{endpoint}?{q}").decode())
    return [h for h in data["data"]["hits"]]


def _in(field: str, values: list[str]) -> dict:
    return {"op": "in", "content": {"field": field, "value": values}}


def fetch_pathology_reports(barcodes: list[str]) -> dict[str, str]:
    """Map barcode -> extracted pathology report text (GDC open-access PDFs)."""
    hits = gdc_query(
        "files",
        {"op": "and", "content": [
            _in("cases.submitter_id", barcodes),
            _in("data_type", ["Pathology Report"]),
            _in("access", ["open"]),
        ]},
        ["file_id", "file_name", "cases.submitter_id"],
        size=len(barcodes) * 4,
    )
    # Deterministic: one report per patient, ties broken by file_name.
    files: dict[str, str] = {}
    for h in sorted(hits, key=lambda h: h["file_name"]):
        bc = h["cases"][0]["submitter_id"]
        files.setdefault(bc, h["file_id"])

    reports: dict[str, str] = {}
    for bc in barcodes:
        file_id = files.get(bc)
        if not file_id:
            print(f"  WARNING: no open pathology report PDF for {bc}", file=sys.stderr)
            continue
        pdf = _request(f"{GDC_API}/data/{file_id}")
        pages = PdfReader(io.BytesIO(pdf)).pages
        text = re.sub(r"\s+", " ", " ".join(p.extract_text() or "" for p in pages)).strip()
        reports[bc] = text
    return reports


def fetch_clinical(barcodes: list[str]) -> dict[str, dict]:
    """Map barcode -> lung diagnosis fields + smoking history (GDC /cases)."""
    hits = gdc_query(
        "cases",
        _in("submitter_id", barcodes),
        ["submitter_id",
         "diagnoses.tissue_or_organ_of_origin",
         "diagnoses.ajcc_pathologic_stage",
         "diagnoses.ajcc_pathologic_t",
         "diagnoses.ajcc_pathologic_n",
         "diagnoses.ajcc_pathologic_m",
         "exposures.pack_years_smoked"],
        size=len(barcodes),
    )
    clinical: dict[str, dict] = {}
    for h in hits:
        # A patient can carry multiple diagnosis records (e.g. a prior tumor);
        # pick the staged lung diagnosis, deterministically.
        lung = sorted(
            (d for d in h.get("diagnoses", [])
             if "lung" in (d.get("tissue_or_organ_of_origin") or "").lower()
             and d.get("ajcc_pathologic_stage")),
            key=lambda d: (d["ajcc_pathologic_stage"],
                           d.get("tissue_or_organ_of_origin") or ""),
        )
        if not lung:
            continue
        row = dict(lung[0])
        packs = [e.get("pack_years_smoked") for e in h.get("exposures", [])
                 if e.get("pack_years_smoked") is not None]
        if packs:
            row["pack_years_smoked"] = packs[0]
        clinical[h["submitter_id"]] = row
    return clinical


def _clinical_summary(c: dict) -> str:
    # Deliberately excludes the diagnosis wording so item_diagnosis evidence stays
    # unique to the pathology_report element (clean information-value curves).
    parts = ["Clinical summary (from TCGA structured data)."]
    site = c.get("tissue_or_organ_of_origin")
    if site:
        parts.append(f"Primary site: {site}.")
    stage = c.get("ajcc_pathologic_stage")
    if stage:
        t, n, m = c.get("ajcc_pathologic_t"), c.get("ajcc_pathologic_n"), c.get("ajcc_pathologic_m")
        tnm = " / ".join(x for x in [t, n, m] if x)
        parts.append(f"AJCC pathologic stage: {stage}." + (f" TNM: {tnm}." if tnm else ""))
    py = c.get("pack_years_smoked")
    if py:
        parts.append(f"Smoking history: {py} pack-years.")
    return " ".join(parts)


def fetch_molecular(barcode: str) -> list[str]:
    """Best-effort: somatic mutated genes for the primary tumor from cBioPortal."""
    sample = f"{barcode}-01"
    url = ("https://www.cbioportal.org/api/molecular-profiles/"
           "luad_tcga_mutations/mutations/fetch?projection=DETAILED")
    body = json.dumps({"sampleIds": [sample],
                       "entrezGeneIds": list(ACTIONABLE_GENES.values())}).encode()
    try:
        muts = json.loads(_request(url, body, "application/json").decode())
    except Exception:
        return []
    genes = []
    for m in muts:
        g = (m.get("gene") or {}).get("hugoGeneSymbol")
        if g and g not in genes:
            genes.append(g)
    return genes


def build_case(barcode: str, clinical: dict, report: str) -> dict:
    elements = {"pathology_report": report, "clinical_summary": _clinical_summary(clinical)}
    ground_truth: dict = {}

    if DIAGNOSIS_TOKEN in report.lower():
        ground_truth["item_diagnosis"] = {"evidence": [DIAGNOSIS_TOKEN]}
    stage = clinical.get("ajcc_pathologic_stage")
    if stage:
        ground_truth["item_staging"] = {"evidence": [stage]}

    genes = fetch_molecular(barcode)
    if genes:
        actionable = [g for g in ACTIONABLE_GENES if g in genes]
        shown = (actionable or genes)[:6]
        elements["molecular_report"] = (
            "NGS panel (public TCGA / cBioPortal, luad_tcga). Somatic mutations "
            f"detected: {', '.join(shown)}."
        )
        marker = (actionable or shown)[0]
        ground_truth["item_molecular"] = {"evidence": [marker]}

    return {"case_id": barcode.replace("-", "_"), "elements": elements, "ground_truth": ground_truth}


def main() -> int:
    print("Fetching TCGA-LUAD clinical records from GDC ...")
    clinical = fetch_clinical(BARCODES)
    print("Fetching pathology report PDFs from GDC open-access tier ...")
    reports = fetch_pathology_reports(BARCODES)

    selected = []
    for bc in BARCODES:
        report = reports.get(bc, "")
        if bc not in clinical:
            print(f"  WARNING: no staged lung diagnosis for {bc}; skipping", file=sys.stderr)
            continue
        if len(report) < 200 or DIAGNOSIS_TOKEN not in report.lower():
            print(f"  WARNING: pathology text failed validation for {bc}; skipping",
                  file=sys.stderr)
            continue
        selected.append((bc, clinical[bc], report))
        print(f"  selected {bc}  stage={clinical[bc].get('ajcc_pathologic_stage')}"
              f"  (report {len(report)} chars)")

    if len(selected) < len(BARCODES):
        print(f"Only {len(selected)}/{len(BARCODES)} cases passed — refusing to "
              "write a partial casebank.", file=sys.stderr)
        return 1

    CASES_DIR.mkdir(parents=True, exist_ok=True)
    for existing in CASES_DIR.glob("*.json"):
        existing.unlink()
    for bc, clin, report in selected:
        case = build_case(bc, clin, report)
        (CASES_DIR / f"{case['case_id']}.json").write_text(
            json.dumps(case, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    print(f"\nWrote {len(selected)} cases to {CASES_DIR}")
    print("Selected barcodes:", ", ".join(bc for bc, _, _ in selected))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
